INSERT INTO asistencias (empleado_id, fecha, estado, unidades)
SELECT e.id, CURDATE() - INTERVAL d.n DAY,
       CASE WHEN MOD(e.id * 7 + d.n, 11) = 0 THEN 'ausente'
            WHEN MOD(e.id * 5 + d.n, 6) = 0  THEN 'tarde'
            ELSE 'presente' END,
       CASE WHEN MOD(e.id * 7 + d.n, 11) = 0 THEN 0 ELSE 20 + MOD(e.id * 13 + d.n * 5, 25) END
FROM empleados e
CROSS JOIN (SELECT 0 AS n UNION SELECT 1 UNION SELECT 2 UNION SELECT 3 UNION SELECT 4 UNION SELECT 5 UNION SELECT 6) d;

