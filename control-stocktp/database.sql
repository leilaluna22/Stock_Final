-- Datos del comercio (una sola fila)
CREATE TABLE comercio (
  id          INT          NOT NULL PRIMARY KEY,
  nombre      VARCHAR(80)  NOT NULL,
  descripcion TEXT         NOT NULL,
  integrantes VARCHAR(120) NOT NULL DEFAULT '',
  ingreso     TEXT         NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Artículos del comercio (no hay límite de cantidad)
CREATE TABLE articulos (
  id            INT         NOT NULL AUTO_INCREMENT PRIMARY KEY,
  codigo        VARCHAR(20) NOT NULL UNIQUE,
  nombre        VARCHAR(80) NOT NULL,
  categoria     VARCHAR(40) NOT NULL DEFAULT 'Sin categoría',
  stock_inicial INT         NOT NULL DEFAULT 0,
  stock_minimo  INT         NOT NULL DEFAULT 5,
  creado        TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (stock_inicial >= 0),
  CHECK (stock_minimo >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- Entradas (ingresos) y salidas (egresos) de mercadería
CREATE TABLE movimientos (
  id          INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,
  articulo_id INT          NOT NULL,
  fecha       DATE         NOT NULL,
  tipo        ENUM('entrada','salida') NOT NULL,
  cantidad    INT          NOT NULL,
  nota        VARCHAR(80)  NOT NULL DEFAULT '',
  creado      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_fecha (fecha),
  INDEX idx_articulo_fecha (articulo_id, fecha),
  CONSTRAINT fk_mov_articulo FOREIGN KEY (articulo_id) REFERENCES articulos(id) ON DELETE CASCADE,
  CHECK (cantidad > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

