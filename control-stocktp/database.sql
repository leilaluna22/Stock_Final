-- =====================================================
CREATE TABLE empleados (
  id            INT           NOT NULL AUTO_INCREMENT PRIMARY KEY,
  nombre        VARCHAR(80)   NOT NULL,
  cargo         VARCHAR(60)   NOT NULL DEFAULT '',
  sueldo_basico DECIMAL(12,2) NOT NULL,
  ingreso       DATE          NOT NULL,
  activo        TINYINT(1)    NOT NULL DEFAULT 1,
  CHECK (sueldo_basico >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE asistencias (
  id          INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
  empleado_id INT  NOT NULL,
  fecha       DATE NOT NULL,
  estado      ENUM('presente','tarde','ausente') NOT NULL,
  unidades    INT  NOT NULL DEFAULT 0,
  UNIQUE KEY uq_emp_fecha (empleado_id, fecha),
  CONSTRAINT fk_asis_emp FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE licencias (
  id          INT  NOT NULL AUTO_INCREMENT PRIMARY KEY,
  empleado_id INT  NOT NULL,
  tipo        ENUM('vacaciones','enfermedad','estudio','otra') NOT NULL,
  desde       DATE NOT NULL,
  hasta       DATE NOT NULL,
  nota        VARCHAR(80) NOT NULL DEFAULT '',
  CONSTRAINT fk_lic_emp FOREIGN KEY (empleado_id) REFERENCES empleados(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

